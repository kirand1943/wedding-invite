"""Generate the hosting config for the platform chosen in deploy.config.json.

    python3 tools/deploy.py            # apply the platform set in deploy.config.json
    python3 tools/deploy.py netlify    # one-off override (also rewrites deploy.config.json)

Options: vercel | netlify | github-pages
Only the chosen platform's file is kept; the other generated files are removed.
  vercel        -> vercel.json
  netlify       -> netlify.toml
  github-pages  -> .github/workflows/pages.yml   (GitHub Pages cannot set cache headers)
Everything is published from "outputDir" (the site/ folder); elements/, tools/ and apps-script/ stay private.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = ROOT / "deploy.config.json"
PLATFORMS = ("vercel", "netlify", "github-pages")


def vercel(c):
    return json.dumps({
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "framework": None,
        "buildCommand": None,
        "installCommand": None,
        "outputDirectory": c["outputDir"],
        "headers": [
            {"source": "/assets/(.*)", "headers": [{"key": "Cache-Control", "value": f"public, max-age={c['assetsCacheSeconds']}"}]},
            {"source": "/vendor/(.*)", "headers": [{"key": "Cache-Control", "value": f"public, max-age={c['vendorCacheSeconds']}, immutable"}]},
        ],
    }, indent=2) + "\n"


def netlify(c):
    return f'''# Generated by tools/deploy.py from deploy.config.json - edit that file, not this one.
[build]
  publish = "{c['outputDir']}"

[[headers]]
  for = "/assets/*"
  [headers.values]
    Cache-Control = "public, max-age={c['assetsCacheSeconds']}"

[[headers]]
  for = "/vendor/*"
  [headers.values]
    Cache-Control = "public, max-age={c['vendorCacheSeconds']}, immutable"
'''


def pages(c):
    return f'''# Generated by tools/deploy.py from deploy.config.json - edit that file, not this one.
# Enable it once: GitHub repo -> Settings -> Pages -> Source: "GitHub Actions".
name: Deploy to GitHub Pages
on:
  push:
    branches: [main]
  workflow_dispatch:
permissions:
  contents: read
  pages: write
  id-token: write
concurrency:
  group: pages
  cancel-in-progress: true
jobs:
  deploy:
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: ${{{{ steps.deployment.outputs.page_url }}}}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/configure-pages@v5
      - uses: actions/upload-pages-artifact@v3
        with:
          path: {c['outputDir']}
      - id: deployment
        uses: actions/deploy-pages@v4
'''


FILES = {
    "vercel": ("vercel.json", vercel),
    "netlify": ("netlify.toml", netlify),
    "github-pages": (".github/workflows/pages.yml", pages),
}


def main():
    cfg = json.loads(CFG.read_text())
    if len(sys.argv) > 1:
        cfg["platform"] = sys.argv[1]
        CFG.write_text(json.dumps(cfg, indent=2) + "\n")
    choice = cfg["platform"]
    if choice not in PLATFORMS:
        sys.exit(f'Unknown platform "{choice}". Choose one of: {", ".join(PLATFORMS)}')
    if not (ROOT / cfg["outputDir"] / "index.html").exists():
        sys.exit(f'{cfg["outputDir"]}/index.html not found')
    for name, (rel, make) in FILES.items():
        path = ROOT / rel
        if name == choice:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(make(cfg))
            print("wrote  ", rel)
        elif path.exists():
            path.unlink()
            print("removed", rel)
            if path.parent.name == "workflows" and not any(path.parent.iterdir()):
                path.parent.rmdir()
                if not any(path.parent.parent.iterdir()):
                    path.parent.parent.rmdir()
    print(f"Platform: {choice}")


main()
